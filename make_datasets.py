"""Build datasets.js, the index behind the "Dane" tab.

Usage:
    python make_datasets.py

Scans data/ for .csv files and writes datasets.js with one entry per file:
size, row count, columns, the time range, and the first few rows as a
preview. The page shows all of that without downloading the file itself -
only the download button fetches the real thing.

Drop a new CSV into data/, re-run this, and the tab picks it up.
"""
import io
import json
import os
import re

DATA_DIR = "data"
PREVIEW_ROWS = 5


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return ("%.0f %s" if unit == "B" else "%.1f %s") % (n, unit)
        n /= 1024.0


def describe(path):
    name = os.path.basename(path)
    size = os.path.getsize(path)

    with io.open(path, encoding="utf-8", errors="replace") as f:
        header = f.readline().rstrip("\n").rstrip("\r")
        cols = [c.strip() for c in header.split(",")]
        preview, first_row, last_row, rows = [], None, None, 0
        for line in f:
            line = line.rstrip("\n").rstrip("\r")
            if not line:
                continue
            rows += 1
            if rows <= PREVIEW_ROWS:
                preview.append(line.split(","))
            if first_row is None:
                first_row = line
            last_row = line

    def first_field(row):
        return row.split(",")[0] if row else ""

    # symbol / timeframe from names like "DE30.pro_M1_20261029T180815Z.csv"
    stem = re.sub(r"\.csv$", "", name, flags=re.I)
    # "_" is a word character, so \b will not fire between "M1" and "_"
    m = re.match(r"(.+?)_(MN\d*|[MHDW]\d*)(?=_|$)", stem)
    symbol = m.group(1) if m else stem
    timeframe = m.group(2) if m else ""

    return {
        "file": name,
        "path": DATA_DIR + "/" + name,
        "symbol": symbol,
        "timeframe": timeframe,
        "bytes": size,
        "size": human(size),
        "rows": rows,
        "columns": cols,
        "firstTime": first_field(first_row),
        "lastTime": first_field(last_row),
        "preview": preview,
    }


def main():
    if not os.path.isdir(DATA_DIR):
        raise SystemExit("Brak folderu %s/" % DATA_DIR)

    files = sorted(f for f in os.listdir(DATA_DIR) if f.lower().endswith(".csv"))
    if not files:
        raise SystemExit("Brak plikow .csv w %s/" % DATA_DIR)

    sets = []
    for f in files:
        d = describe(os.path.join(DATA_DIR, f))
        sets.append(d)
        print("%-46s %8s  %7d wierszy  %s -> %s"
              % (d["file"][:44], d["size"], d["rows"], d["firstTime"][:19], d["lastTime"][:19]))

    nl = chr(10)
    with io.open("datasets.js", "w", encoding="utf-8") as out:
        out.write("// Auto-generated by make_datasets.py - do not edit." + nl)
        out.write("// Plain script (not a module) so data.html works from disk." + nl)
        out.write("var DATASETS = " + json.dumps(sets, ensure_ascii=False, indent=1) + ";" + nl)

    total = sum(d["bytes"] for d in sets)
    print(nl + "datasets.js: %d zbior(ow), %s lacznie." % (len(sets), human(total)))


if __name__ == "__main__":
    main()
